"""Build a manifest of Russian speech clips from the learning curriculum.
Speech is generated by a Russian neural voice; no browser TTS is used.
"""
import asyncio
import hashlib
import json
import re
from pathlib import Path
import edge_tts

ROOT=Path(__file__).resolve().parents[1]
FILES=["curriculum/a1-alphabet.js","curriculum/visual-vocabulary.js","curriculum/a1-reading.js","curriculum/a2-lessons.js","curriculum/a2-reading.js","curriculum/a2-dialogues.js","curriculum/a2-listening.js"]
RU=re.compile(r"[А-Яа-яЁё]")
def phrases():
    results=set()
    # Match quoted Russian phrases in JS; the files are authored with literal Russian text.
    for name in FILES:
        raw=(ROOT/name).read_text(encoding="utf-8")
        for match in re.finditer(r'(?P<q>["\x27])(?P<s>[^"\x27\n]{1,700})(?P=q)',raw):
            phrase=match.group("s").strip()
            if RU.search(phrase) and not re.search(r"[\u0600-\u06ff]",phrase) and len(phrase)<450:
                results.add(phrase)
    # Alphabet recordings read the letter name in a short phrase.
    letters=json.loads((ROOT/"curriculum/a1-alphabet.js").read_text(encoding="utf-8").split("=",1)[1].strip().rstrip(";"))
    return sorted(results),[item["letter"].split()[0] for item in letters]
# Spoken Russian letter names, without the preceding word "Буква".
# Ъ and Ь are signs, not independent phonemes; their conventional names are spoken.
LETTER_NAMES=["а","бэ","вэ","гэ","дэ","е","ё","жэ","зэ","и","и краткое","ка","эль","эм","эн","о","пэ","эр","эс","тэ","у","эф","ха","цэ","че","ша","ща","твёрдый знак","ы","мягкий знак","э","ю","я"]
async def main():
    phrases_list,letters=phrases()
    folder=ROOT/"audio/neural"
    folder.mkdir(parents=True,exist_ok=True)
    manifest={}
    for i,phrase in enumerate(phrases_list):
        name="curriculum-"+hashlib.sha256(phrase.encode()).hexdigest()[:16]+".mp3"
        path=folder/name
        if not path.exists() or path.stat().st_size<1000:
            await edge_tts.Communicate(phrase,"ru-RU-SvetlanaNeural").save(str(path))
        manifest[phrase]="audio/neural/"+name
    alphabet={}
    assert len(letters)==len(LETTER_NAMES)==33
    for i,(letter,spoken_name) in enumerate(zip(letters,LETTER_NAMES),1):
        path=folder/f"letter-isolated-{i:02d}.mp3"
        if not path.exists() or path.stat().st_size<1000:
            await edge_tts.Communicate(spoken_name,"ru-RU-SvetlanaNeural").save(str(path))
        alphabet[letter]="audio/neural/"+path.name
    assert len(alphabet)==33
    for filename,var,items in [
      ("alphabet-neural-audio.js","LEXORA_ALPHABET_AUDIO",alphabet),
      ("curriculum-neural-audio.js","LEXORA_CURRICULUM_AUDIO",manifest)
    ]:
        (ROOT/filename).write_text("window."+var+" = "+json.dumps(items,ensure_ascii=False,indent=2)+";\n",encoding="utf-8")
    print("Generated/verified",len(manifest),"curriculum clips and",len(alphabet),"alphabet clips")
if __name__=="__main__":
    asyncio.run(main())

