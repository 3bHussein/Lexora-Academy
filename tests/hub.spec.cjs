const {test,expect}=require('@playwright/test');
const base='http://127.0.0.1:4173';
test('hub lessons, PTE feedback, persistence and mobile layout',async({page})=>{
 await page.goto(base+'/academy.html');
 await page.getByRole('button',{name:'Start German',exact:true}).click();
 await page.getByRole('button',{name:'Ich heiße Anna.',exact:true}).click();
 await expect(page.locator('#lessonPanel')).toContainText('Correct!');
 await page.getByRole('button',{name:'Start Italian',exact:true}).click();
 await page.getByRole('button',{name:'Grazie',exact:true}).click();
 await page.getByRole('button',{name:'Practice reading',exact:true}).click();
 await page.getByRole('button',{name:'retention',exact:true}).click();
 await expect(page.locator('#ptePanel')).toContainText('Try again');
 await page.getByRole('button',{name:'retain',exact:true}).click();
 await expect(page.locator('#stats')).toContainText('3');
 await page.getByRole('button',{name:'Practice writing',exact:true}).click();
 await page.getByRole('button',{name:'Check form',exact:true}).click();
 await expect(page.locator('#ptePanel')).toContainText('Use 5–75 words');
 await page.getByLabel('Summarize the passage').fill('Urban trees cool cities and absorb rainfall, but need suitable species and maintenance.');
 await page.getByRole('button',{name:'Check form',exact:true}).click();
 await expect(page.locator('#ptePanel')).toContainText('Basic length and sentence checks passed');
 await page.getByText('Review model and self-assess',{exact:true}).click();
 await page.getByRole('button',{name:'Mark reviewed',exact:true}).click();
 await page.reload();
 await expect(page.locator('#stats article').first()).toContainText('4');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.goto(base+'/index.html');
 await expect(page.getByRole('link',{name:/Languages & PTE Hub/})).toHaveAttribute('href','academy.html');
});
test('corrupted progress does not break hub',async({page})=>{await page.goto(base+'/academy.html');await page.evaluate(()=>localStorage.setItem('lexoraHubV1','broken'));await page.reload();await expect(page.locator('#stats article').first()).toContainText('0');});
